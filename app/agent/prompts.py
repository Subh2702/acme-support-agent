def build_context(
    state: ConversationState,
    *,
    now_ist: str,
    notes: list[str],
    escalation_ticket: int | None,
) -> str:
    identity = (
        f"VERIFIED as {state.verified_name} (customer #{state.verified_customer_id})"
        if state.is_verified
        else "NOT VERIFIED"
    )
    lines = [
        "## Conversation context (generated by the system, trustworthy)",
        f"- Current time: {now_ist}",
        f"- Customer identity: {identity}",
        f"- Failed verification attempts: {state.failed_verifications}",
        f"- Reply language: {'Hinglish' if state.language == 'hinglish' else 'English'}",
    ]
    if escalation_ticket is not None:
        lines.append(
            f"- This conversation is escalated to a human (ticket #{escalation_ticket}); a "
            "specialist will follow up. Keep helping with questions."
        )
    done = [a for a in state.actions if a.outcome == "done"]
    if done:
        lines.append(
            "- Actions completed earlier: "
            + "; ".join(f"{a.tool} {a.order_number}: {a.detail}" for a in done[-5:])
        )
    lines.extend(f"- NOTE: {n}" for n in notes)
    return "\n".join(lines)


